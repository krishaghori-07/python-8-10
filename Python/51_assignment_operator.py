#shopping bill management system
total=1000

print("intial shopping amount",total)

#addition assignment
total+=500
print("after adding clothes:",total)

#subtraction assignment
total-=200
print("after applying discount:",total)

#multiplication assignment
total*=2
print("after buying two sets:",total)

#division assignment
total/=2
print("after dividing the bill:",total)

#floor division assignment
total//=3
print("after splitting among 3 persons:",total)

#modulus assignment
total%=100
print("remaining amount:",total)

#exponent assignment
total**=2
print("final amount after square:",total)